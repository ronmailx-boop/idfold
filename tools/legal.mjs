// Builds the public legal pages (privacy.html, terms.html, cookies.html, accessibility.html)
// from docs/legal/*.md. Run after editing a document: npm run legal
import { readFileSync, writeFileSync } from 'node:fs';

const PAGES = [
  { src: 'privacy-policy.md', out: 'privacy.html', nav: 'פרטיות' },
  { src: 'terms-of-service.md', out: 'terms.html', nav: 'תנאי שימוש' },
  { src: 'cookie-policy.md', out: 'cookies.html', nav: 'עוגיות' },
  { src: 'accessibility-statement.md', out: 'accessibility.html', nav: 'נגישות' }
];

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function inline(text) {
  return esc(text)
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/`(.+?)`/g, '<code dir="ltr">$1</code>')
    .replace(/\[(.+?)\]\((.+?)\)/g, (_, label, href) => /^https?:/.test(href)
      ? `<a href="${href}" target="_blank" rel="noopener">${label}</a>`
      : `<a href="${href}">${label}</a>`);
}

// Supports what the documents use: # and ## headings, "- " lists, paragraphs
// (lines inside a paragraph are kept as line breaks), **bold**, `code` and [links](url).
function render(md) {
  const out = [];
  let title = '';
  for (const block of md.trim().split(/\n\s*\n/)) {
    const lines = block.split('\n');
    if (lines[0].startsWith('# ')) {
      title = lines[0].slice(2);
      out.push(`<h1>${inline(title)}</h1>`);
    } else if (lines[0].startsWith('## ')) {
      out.push(`<h2>${inline(lines[0].slice(3))}</h2>`);
      if (lines.length > 1) out.push(...render(lines.slice(1).join('\n')).html);
    } else if (lines.every((l) => l.startsWith('- '))) {
      out.push(`<ul>\n${lines.map((l) => `  <li>${inline(l.slice(2))}</li>`).join('\n')}\n</ul>`);
    } else if (lines.length > 1 && lines.slice(1).every((l) => l.startsWith('- '))) {
      out.push(`<p>${inline(lines[0])}</p>`, ...render(lines.slice(1).join('\n')).html);
    } else {
      out.push(`<p>${lines.map(inline).join('<br>\n')}</p>`);
    }
  }
  return { title, html: out };
}

function page({ out }, { title, html }) {
  const nav = PAGES.map((p) => p.out === out
    ? `<a aria-current="page">${p.nav}</a>`
    : `<a href="${p.out}">${p.nav}</a>`).join('\n      ');
  return `<!doctype html>
<!-- Generated by tools/legal.mjs from docs/legal. Do not edit by hand. -->
<html lang="he" dir="rtl">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'self'; font-src 'self'; img-src 'self'; base-uri 'none'; form-action 'none'">
  <title>${esc(title)} · IDfold</title>
  <link rel="icon" href="icons/icon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="css/fonts.css">
  <link rel="stylesheet" href="css/legal.css">
</head>
<body>
  <header>
    <a class="brand" href="./"><img src="icons/icon.svg" alt="" width="32" height="32">IDfold</a>
    <nav aria-label="מסמכים">
      ${nav}
    </nav>
  </header>
  <main>
    ${html.join('\n    ')}
  </main>
  <footer><a href="./">חזרה לאפליקציה</a></footer>
</body>
</html>
`;
}

for (const p of PAGES) {
  const doc = render(readFileSync(new URL(`../docs/legal/${p.src}`, import.meta.url), 'utf8'));
  writeFileSync(new URL(`../${p.out}`, import.meta.url), page(p, doc));
}
console.log(`built ${PAGES.map((p) => p.out).join(', ')}`);
